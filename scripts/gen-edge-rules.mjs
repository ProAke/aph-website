#!/usr/bin/env node
/**
 * Generates the edge router config for a given rollout percentage, so every canary step is an
 * explicit, reviewable file instead of a hand-edited number.
 *
 *   npm run edge:gen -- --rollout 5      → deploy/generated/aph-edge-5.conf   (5 % on Nuxt)
 *   npm run edge:gen -- --rollout 100    → full cut-over
 *   npm run edge:gen -- --rollout 0      → instant rollback to WordPress
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises'

const argv = process.argv.slice(2)
function arg(name, fallback = '') {
  const eq = argv.find((a) => a.startsWith(`--${name}=`))
  if (eq) return eq.split('=').slice(1).join('=')
  const idx = argv.indexOf(`--${name}`)
  if (idx !== -1 && argv[idx + 1] && !argv[idx + 1].startsWith('--')) return argv[idx + 1]
  return fallback
}

const rollout = Number(arg('rollout', '0'))
if (!Number.isInteger(rollout) || rollout < 0 || rollout > 100) {
  console.error('✖ --rollout must be an integer between 0 and 100 (e.g. --rollout 5)')
  process.exit(1)
}

const template = await readFile(new URL('../deploy/nginx/aph-edge.conf', import.meta.url), 'utf8')

const splitBlock = `split_clients "\${remote_addr}\${http_user_agent}\${date_gmt}" $aph_bucket {
    ${String(rollout).padStart(3)}%      new;
    *       legacy;
}`

let generated = template.replace(
  'map $host $aph_rollout { default 0; }          # ← generated value',
  `map $host $aph_rollout { default ${rollout}; }          # ← generated: ${rollout}% of visitors on Nuxt`
)
const before = generated
generated = generated.replace(/split_clients[^\n]*\n[\s\S]*?\n\}/, splitBlock)
if (generated === before) {
  console.error('✖ could not find the split_clients block in the template — template changed?')
  process.exit(1)
}

const outFile = new URL(`../deploy/generated/aph-edge-${rollout}.conf`, import.meta.url)
await mkdir(new URL('../deploy/generated/', import.meta.url), { recursive: true })
await writeFile(outFile, `# generated by scripts/gen-edge-rules.mjs — rollout ${rollout}%\n${generated}`)

console.log(`✔ deploy/generated/aph-edge-${rollout}.conf`)
console.log(`  deploy : sudo cp deploy/generated/aph-edge-${rollout}.conf /etc/nginx/conf.d/aph-edge.conf`)
console.log(`           sudo nginx -t && sudo nginx -s reload`)
console.log(`  verify : curl -sI https://www.aph-ita.co.th/ | grep -i x-aph`)
if (rollout === 0) console.log('  ⚠ ROLLBACK config — 100 % of traffic goes back to WordPress')
if (rollout === 100) console.log('  ✓ FULL CUT-OVER — WordPress stays warm for instant rollback')
