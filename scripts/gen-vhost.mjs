#!/usr/bin/env node
/**
 * Generates an nginx vhost for ONE sub-domain of the migration — so “เพิ่มอีก sub-domain”
 * is a single command instead of hand-copying a config and forgetting the noindex header.
 *
 *   npm run vhost:gen -- --host staging.aph-ita.co.th --mode staging        # Basic Auth + noindex
 *   npm run vhost:gen -- --host uat.aph-ita.co.th     --mode uat            # no auth, still noindex
 *   npm run vhost:gen -- --host new.aph-ita.co.th     --mode redirect       # 301 → www (retire)
 *   npm run vhost:gen -- --host beta.aph-ita.co.th --mode staging --port 3010
 *
 * Modes
 *   staging  Basic Auth + noindex + no cache + upstream error shown (you want to see breakage)
 *   uat      no password (share the link with a customer) + noindex + no cache
 *   redirect 301 everything to https://www.aph-ita.co.th (after cut-over)
 */
import { writeFile, mkdir, readFile } from 'node:fs/promises'
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'

const argv = process.argv.slice(2)
function arg(name, fallback = '') {
  const eq = argv.find((a) => a.startsWith(`--${name}=`))
  if (eq) return eq.split('=').slice(1).join('=')
  const idx = argv.indexOf(`--${name}`)
  if (idx !== -1 && argv[idx + 1] && !argv[idx + 1].startsWith('--')) return argv[idx + 1]
  return fallback
}

const MODES = ['staging', 'uat', 'redirect']
const AUTH_FILE = arg('auth-file', '/etc/nginx/.htpasswd-aph')
const REDIRECT_TO = arg('redirect-to', 'https://www.aph-ita.co.th').replace(/\/$/, '')
const OUT_DIR = arg('out', 'deploy/generated')
const ALL = argv.includes('--all')
const ENV_FILE = arg('env-file', 'deploy/environments.json')

const hostRe = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/

function validate({ host, mode, port }) {
  if (!hostRe.test(String(host || ''))) throw new Error(`--host must be a DNS name, got "${host}"`)
  if (!MODES.includes(mode)) throw new Error(`--mode must be one of: ${MODES.join(', ')}`)
  if (mode !== 'redirect' && (!Number.isInteger(port) || port < 1 || port > 65535)) {
    throw new Error('--port must be a valid TCP port (default 3000)')
  }
}

function render({ host, mode, port }) {
  const HOST = host
  const MODE = mode
  const PORT = port
  const upstreamName = `aph_${HOST.split('.')[0].replace(/[^a-z0-9]/g, '_')}`
  const slug = HOST.split('.')[0]

const head = (host, title, note) => `# ════════════════════════════════════════════════════════════════════════════
#  ${host} — ${title}
#
#  ${note}
#  Generated by scripts/gen-vhost.mjs (mode: ${MODE}) — edit the generator, not this file,
#  so every environment keeps the same noindex / auth / cache rules.
#
#  Install:
#    sudo cp ${OUT_DIR}/${host}.conf /etc/nginx/sites-available/${host}
#    sudo ln -sf /etc/nginx/sites-available/${host} /etc/nginx/sites-enabled/${host}
#    sudo certbot --nginx -d ${host} --redirect
#    sudo nginx -t && sudo nginx -s reload
# ════════════════════════════════════════════════════════════════════════════
`

let conf
if (MODE === 'redirect') {
  conf = `${head(HOST, 'retired sub-domain', 'Everything 301s to the canonical production host, so old links and bookmarks keep working.')}
server {
    listen 80;
    listen 443 ssl http2;
    server_name ${HOST};

    ssl_certificate     /etc/letsencrypt/live/${HOST}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/${HOST}/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;

    # 301 (not 302): the move is permanent, and search engines should transfer the signals
    return 301 ${REDIRECT_TO}$request_uri;
}
`
} else {
  const authBlock =
    MODE === 'staging'
      ? `    # Basic Auth — keep strangers out during UAT
    auth_basic           "APH ${slug}";
    auth_basic_user_file ${AUTH_FILE};
`
      : `    # mode=uat: no password, so a customer can open the link directly.
    # The noindex layers below are what keep it out of Google.
`
  conf = `${head(
    HOST,
    MODE === 'staging' ? 'staging / internal review' : 'customer UAT preview',
    MODE === 'staging'
      ? 'Basic Auth + four noindex layers. Nothing here can reach Google or a CDN cache.'
      : 'Public link (no password) but still noindex — share it with a customer for sign-off.'
  )}
upstream ${upstreamName} {
    server 127.0.0.1:${PORT} max_fails=2 fail_timeout=10s;
    keepalive 32;
}

server {
    listen 80;
    server_name ${HOST};
    return 301 https://$host$request_uri;      # certbot replaces this block
}

server {
    listen 443 ssl http2;
    server_name ${HOST};

    ssl_certificate     /etc/letsencrypt/live/${HOST}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/${HOST}/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;

${authBlock}
    # ── noindex layers (the app adds meta robots + robots.txt) ─────────────
    add_header X-Robots-Tag "noindex, nofollow, noarchive, nosnippet" always;
    add_header X-APH-Env   "${MODE}" always;

    client_max_body_size 25m;
    gzip on;
    gzip_types text/css application/javascript application/json image/svg+xml application/xml;

    # never let a CDN keep a half-finished build
    proxy_no_cache 1;
    proxy_cache_bypass 1;
    add_header Cache-Control "no-store" always;

    location / {
        proxy_http_version 1.1;
        proxy_set_header Host              $host;
        proxy_set_header X-Real-IP         $remote_addr;
        proxy_set_header X-Forwarded-For   $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header X-Forwarded-Host  $host;

        proxy_pass http://${upstreamName};
        proxy_connect_timeout 3s;
        proxy_read_timeout    30s;

        # during UAT you want the error, not a silent fallback to WordPress
        proxy_intercept_errors off;
    }
}
`
}

  return conf
}

// cheap structural check — nginx itself will still be the final word (nginx -t on the server)
function checkBalance(text, label) {
  const balance = [...text].reduce((n, ch) => n + (ch === '{' ? 1 : ch === '}' ? -1 : 0), 0)
  if (balance !== 0) throw new Error(`generated config for ${label} has unbalanced braces`)
}

async function emit(target) {
  validate(target)
  const conf = render(target)
  checkBalance(conf, target.host)
  await mkdir(OUT_DIR, { recursive: true })
  const file = `${OUT_DIR}/${target.host}.conf`
  await writeFile(file, conf)
  console.log(`✔ ${file}  (mode=${target.mode}${target.mode === 'redirect' ? '' : ` port=${target.port}`})`)
  return { ...target, file }
}

let emitted = []
try {
  if (ALL) {
    // everything in deploy/environments.json, plus a redirect entry for any host we retired
    const map = JSON.parse(await readFile(ENV_FILE, 'utf8'))
    console.log(`→ ${ENV_FILE}: ${map.environments.length} environment(s) under ${map.domain}\n`)
    for (const env of map.environments) {
      // www is served by the edge router (deploy/nginx/aph-edge.conf), not by a plain vhost
      if (env.mode === 'production') {
        console.log(`⏭  ${env.host}: production — served by deploy/nginx/aph-edge.conf (skipped)`)
        continue
      }
      if (env.indexable) throw new Error(`${env.host} is marked indexable — a pre-cut-over sub-domain must never be indexable`)
      emitted.push(await emit({ host: env.host, mode: env.mode, port: env.port }))
    }
  } else {
    emitted.push(await emit({ host: arg('host', ''), mode: arg('mode', 'staging'), port: Number(arg('port', '3000')) }))
  }
} catch (err) {
  console.error(`✖ ${err.message}`)
  process.exit(1)
}

console.log('\n── ติดตั้งบนเซิร์ฟเวอร์ (ทำตามลำดับ) ──')
for (const e of emitted) {
  console.log(`
# ${e.host}
sudo cp ${e.file} /etc/nginx/sites-available/${e.host}
sudo ln -sf /etc/nginx/sites-available/${e.host} /etc/nginx/sites-enabled/${e.host}
sudo certbot --nginx -d ${e.host} --redirect`)
}
if (emitted.some((e) => e.mode === 'staging')) {
  console.log(`\n# รหัสผ่านของ staging (ครั้งแรกครั้งเดียว)
sudo apt-get install -y apache2-utils && sudo htpasswd -c ${AUTH_FILE} aph`)
}
const ports = emitted.filter((e) => e.mode !== 'redirect').map((e) => e.port)
if (ports.length) {
  console.log(`\nsudo systemctl enable --now ${ports.map((p) => `aph-nuxt@${p}`).join(' ')}`)
}
console.log(`sudo nginx -t && sudo nginx -s reload\n`)

if (argv.includes('--check')) {
  try {
    const { stdout } = await promisify(execFile)('nginx', ['-t'])
    console.log(stdout.trim())
  } catch {
    console.log('  (nginx not installed on this machine — run `sudo nginx -t` on the server)')
  }
}
